// Celular: em pé aparece "Gire o celular" e o jogo para; deitado a tela inicial cabe (título visível) e o jogo anda.
// Uso: node velocista/tools/teste-deitado.mjs [pasta-de-prints]
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { servidor, abrir } from '../../golaco/tools/lib/navegador.mjs';
const AQUI = path.dirname(fileURLToPath(import.meta.url));
const saida = process.argv[2];
let falhas = 0;
const ok = (c, msg) => { console.log(`${c ? 'OK ' : 'ERRO'} ${msg}`); if (!c) falhas++; };
const srv = await servidor(0, path.join(AQUI, '..'));
const { navegador, pagina, erros } = await abrir({ largura: 390, altura: 844, toque: true, dpr: 2 });
await pagina.goto(srv.url);
await pagina.waitForTimeout(800);
ok(await pagina.isVisible('#girar'), 'em pé: tela "Gire o celular"');
if (saida) await pagina.screenshot({ path: path.join(saida, 'em-pe.png'), timeout: 120000 });
await pagina.setViewportSize({ width: 844, height: 390 });
await pagina.waitForTimeout(400);
ok(!(await pagina.isVisible('#girar')), 'deitado: some o aviso');
const h1 = await pagina.evaluate(() => { const r = document.querySelector('#telaInicio h1').getBoundingClientRect(); return { top: r.top, txt: document.querySelector('#telaInicio h1').textContent }; });
ok(h1.top >= 0 && h1.txt === 'THE FLASH', `título "THE FLASH" inteiro na tela (topo ${h1.top.toFixed(0)} px)`);
await pagina.waitForSelector('#btnJogar:not([hidden])', { timeout: 300000 });
if (saida) await pagina.screenshot({ path: path.join(saida, 'deitado-menu.png'), timeout: 120000 });
await pagina.evaluate(() => document.getElementById('btnJogar').click());
await pagina.waitForFunction(() => window.__rel.P.t > 0.2, null, { timeout: 120000 });
ok(await pagina.evaluate(() => !!document.fullscreenElement), 'COMEÇAR no celular pede tela cheia (Android trava deitado)');
await pagina.evaluate(() => document.fullscreenElement && document.exitFullscreen());
await pagina.waitForTimeout(300);
await pagina.setViewportSize({ width: 390, height: 844 });
await pagina.waitForTimeout(500);
const t0 = await pagina.evaluate(() => window.__rel.P.t);
await pagina.waitForTimeout(2500);
const t1 = await pagina.evaluate(() => window.__rel.P.t);
ok(t1 === t0, `em pé no meio do jogo: parado (t ${t0.toFixed(2)} → ${t1.toFixed(2)})`);
await pagina.setViewportSize({ width: 844, height: 390 });
await pagina.waitForFunction((t) => window.__rel.P.t > t + 0.1, t1, { timeout: 120000 }).catch(() => {});
ok(await pagina.evaluate((t) => window.__rel.P.t > t, t1), 'deitado de novo: o jogo volta a andar');
ok(erros.length === 0, `sem erros no console (${erros.slice(0, 3).join(' | ')})`);
await navegador.close(); await srv.fechar();
process.exit(falhas ? 1 : 0);
